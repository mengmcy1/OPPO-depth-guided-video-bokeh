def rich(par, t):
    for i, seg in enumerate(re.split(r'\*\*', t)):
        if seg: par.add_run(seg).bold = (i % 2 == 1)
def H(t): doc.add_heading(t, level=1)
def S(t): doc.add_heading(t, level=2)
def P(t): rich(doc.add_paragraph(), t)
def B(items):
    for it in items: rich(doc.add_paragraph(style='List Bullet'), it)
def N(items):
    for it in items: rich(doc.add_paragraph(style='List Number'), it)

doc.add_heading('前馈视频高斯光学虚化：思路与可行性验证　讲稿', level=0)
P('配套 PPT：前馈视频虚化思路与验证_1111.pptx（9 页），页序一致。每页分三部分：讲法（照着讲即可）、这页要点（一句话）、如果被问到（只在需要的页给出）。')

