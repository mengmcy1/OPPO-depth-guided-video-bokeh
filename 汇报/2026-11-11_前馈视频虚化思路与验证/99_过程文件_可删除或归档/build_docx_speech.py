B(['**像素锚定是什么？** 可见层的每个高斯对应当前帧的一个像素。几何固定，只优化颜色，让光圈为零时的渲染结果和输入帧一致。这样焦内画质不会被破坏。',
   '**为什么可见层直接用 SHARP？** 第一版重点在隐藏层，可见层用现成方法可以控制工作量，后续需要时再自己训练。'])

H('第 5 页　受控场景：被遮挡层与光圈渲染两项前提成立')
S('讲法')
P('正式做网络之前，我们先在 Blender 里搭了一个受控场景，是一段带物理景深真值的手持视频，分别对焦在 1.4 m 和 5.0 m。用它验证两个前提：')
B(['**被遮挡层确实重要。** 中间这组是 5.0 m 对焦时的前景边缘局部，从左到右依次是物理真值、只有可见层、加入被遮挡层。只有可见层时，边缘一圈是错的；补上真实的被遮挡内容后，就和真值很接近了。在可恢复区域，PSNR 提升 1.9–6.2 dB。',
   '**光圈渲染本身是准的。** 64 个子视角积分和物理真值相比，全图 PSNR 有 52.6 / 53.9 dB，可以认为一致。'])
P('所以只要被遮挡内容找对了，后面的渲染是可以信任的。接下来的问题就是怎么找。')
S('这页要点')
P('两个前提都成立，难点集中在隐藏层。')

H('第 6 页　第一版隐藏层网络')
S('讲法')
P('这是第一版隐藏层网络的结构，上面标着“训练的部分”的两个深色框是要学的。')
N(['从观测记忆出发。记忆里同一个位置可以存多个表面假设，每个观测都记着来自哪一帧、哪个像素。',
   '在光圈去遮挡区里取候选，也就是光圈会看到的前景背后那一圈，每个位置 8 个。',
   '候选分两路解码：几何这一路决定选哪个候选、给出可信度；外观这一路回到来源帧取颜色、做融合。',
   '每个位置输出 2 个隐藏高斯，和可见层按深度合成，做 K=64 物理渲染。'])
P('下面三条是设计时守住的原则：')
B(['**标签按子光圈光线定义。** 判断一个候选对不对，不是看它在中心视角下对不对，而是看它是不是某条子光圈光线真正会打到的表面。虚化本来就是这些光线的平均，所以监督要和渲染方式对齐。',
   '**颜色只取自真实来源帧。** 网络只负责选择、修正和融合，不凭空生成颜色，这样找回来的内容是真实的。',
   '**可信度不乘进不透明度。** 可信度只用来决定选不选、要不要拒绝、要不要交给补全。遮挡关系仍由渲染器按几何来算，不会被可信度二次削弱。'])
S('这页要点')
P('第一版先用轻量候选融合，可见层固定，不参与训练。')
S('如果被问到')
B(['**为什么先用轻量融合？** 先用最简单的选择加权跑通。达到预期就不升级；不够再上带深度修正的完整查询解码。'])

