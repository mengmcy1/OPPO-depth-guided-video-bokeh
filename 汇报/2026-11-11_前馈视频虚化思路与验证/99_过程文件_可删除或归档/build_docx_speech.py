S('讲法')
P('这一页把查询的思路串起来，可以看成上一页的运行逻辑。主链是：观测记忆 → 光圈条件查询 → 联合修正 → 隐藏高斯 → K=64 渲染。')
B(['**观测记忆只存真实观测。** 只有多帧看到、几何一致的内容才写进来。同一位置允许多个表面并存，不强行平均，否则会把前景色混进背景。',
   '**查询只在光圈会看到的地方发起。** 不是整张图都查，只查前景边缘后面那一圈。候选的先后由“光圈可见度”决定：从光圈上的 64 个点向候选发光线，统计有多少条没被前景挡住。被更多子光圈看到的候选，对最终画面影响更大，就优先考虑。',
   '**联合修正是几何和颜色一起改。** 位置修正后，要按新位置回到来源帧重新取颜色。前期发现，取错的往往是另一个物体，深度和颜色都是错的；只改深度、颜色不跟着改，效果反而更差。'])
P('图里的虚线回路比较重要。网络的预测只放在短期缓存里，当前窗口用完就算。只有后来被新的帧真实看到、并验证一致的内容，才写进长期记忆。所以记忆里始终只有事实，不会被网络的错误预测污染。')
S('这页要点')
P('记忆存事实，缓存存预测；光圈决定先看哪个候选。')
S('如果被问到')
B(['**所有帧都没看到的区域怎么办？** 只能交给补全，单独输出置信度并标记为生成内容，评测时不算作恢复。第一版暂不做补全的生成部分。',
   '**和 QuerySplat 的关系？** 借鉴了几何 / 外观双分支解码。区别在于我们的查询位置由光圈去遮挡区决定，候选来自跨帧观测，不是自由的可学习查询。'])

H('第 8 页　跨帧一致的两遍式渲染流程')
S('讲法')
P('视频还有一个单图没有的问题：闪烁。分析下来，大部分闪烁的根源是同一个表面在不同帧被重新估计，每次结果略有不同，看起来就在跳。所以我们用两遍式流程：')
B(['**第一遍，片段级构建。** 对一个视频片段只做一次：把输入帧的真实观测融合成观测记忆，包括世界坐标、表面片段编号和多表面假设。建好之后冻结，不再改动。',
   '**第二遍，逐帧渲染，包括没有作为输入的中间帧。** 可见层用当前帧颜色锚定，深度从记忆里取；隐藏层中已确认的表面直接复用记忆里的同一份；最后按当前焦点和光圈做 K=64 渲染。'])
P('这样同一面墙在整段视频里只有一份几何和外观，一致性从表示层面就保证了，时序损失只作辅助。另外，隐藏层和焦点无关，换焦点、换光圈只需要重跑第二遍的渲染。')
S('这页要点')
P('静态表面整段视频共享同一份几何与外观，从表示层面保证跨帧一致。')
S('如果被问到')
B(['**对焦距离抖动怎么办？** 用户在关键帧点选主体，在逆深度上把对焦距离平滑插值，去掉估计带来的高频抖动。',
   '**隐藏表面在帧间来回切换怎么办？** 用启用 / 停用双阈值：可信度高于 0.6 才启用，低于 0.4 且连续 2 帧才停用，避免在阈值附近来回跳。',
   '**渲染采样会不会抖？** 推理时固定 64 个子光圈位置和权重，不随机采样。',
   '**运动物体边缘呢？** 第一版作为已知局限，留到第二版处理。'])

