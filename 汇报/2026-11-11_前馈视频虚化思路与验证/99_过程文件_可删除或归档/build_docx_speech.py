P('左边是 64 个子视角中的 3 个，前景位置有轻微错动。中间是 64 个视角平均后的结果，右边是物理渲染的真值，两者基本一样。')
P('这件事和 3DGS 很契合。3DGS 渲染任意视角都很便宜，只要有一份场景的高斯表示，按光圈积分就能直接得到虚化。焦点和光圈都只是渲染参数，用户可以随时调整。')
S('这页要点')
P('虚化交给物理渲染，不交给网络去“画”。')

H('第 3 页　前景虚化后会透出被挡住的背景')
S('讲法')
P('这样做有一个关键难点。前景虚化以后，边缘会变得半透明，因为光圈下半部分的光线可以绕过前景，看到它背后的点。')
P('所以要把前景边缘的虚化做对，就必须知道前景背后是什么，MPIB 讨论的也是这个问题。单张图只能补全，等于靠猜。视频不一样，相机在动、人物在动，这些被挡住的内容常常在其他帧里出现过。')
S('这页要点')
P('视频相对单图的价值，在于被遮挡的内容可以从其他帧找回来。')

H('第 4 页　系统构想：可见层锚定当前帧，隐藏层取自视频')
S('讲法')
P('基于前两页，整体系统是这样的。输入是一段手持视频，用户点选要对焦的主体，再给一个光圈大小。')
P('第一步是几何前端：用现成的 DA3 估计深度和位姿，再用稠密光流三角化做多视角校准，让各帧深度一致。后面分三块：')
B(['**可见层**：当前帧看得到的部分，用像素锚定的高斯表示，第一版直接用 SHARP 的几何。',
   '**隐藏层**：前景背后被挡住的部分，是我们主要要做的。通过观测记忆和光圈条件查询，从视频其他帧里找回来。',
   '**物理光圈渲染**：就是第 2 页的做法，每个子相机渲染一张，按深度合成，再平均。思路借鉴光场重对焦。'])
P('输出是一段可以随时改焦点和光圈的虚化视频。')
S('这页要点')
P('网络只负责场景内容，虚化由物理相机决定，换焦点、换光圈只需重新渲染。')
